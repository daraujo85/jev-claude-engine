/** Resolve the current language from config (fallback to default). */
export function currentLang(cfg) {
  const lang = cfg?.ui?.lang || cfg?.language || DEFAULT_LANG;
  return STRINGS[lang] ? lang : DEFAULT_LANG;
}

/** Translate a key in the given language (or current config lang). */
export function t(key, lang) {
  const dict = STRINGS[lang] || STRINGS[DEFAULT_LANG];
  return dict[key] || STRINGS[DEFAULT_LANG][key] || key;
}

/** Format a template string with {placeholders}. */
export function fmt(str, vars) {
  return String(str).replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? vars[k] : `{${k}}`));
}